import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";

import { diffCatalogs, formatDiff, parseCatalog } from "../sync-models.mjs";

// The shape scripts/sync-models.mjs writes to catalog.ts
const CATALOG_TEXT = `// Generated by scripts/sync-models.mjs (npm run sync-models). Do not edit
// by hand. Source: https://models.dev/api.json, read 2026-11-15.
import type { CatalogModel } from "../catalogTypes.js";

export const CATALOG_SYNCED_AT = "2026-11-15";

export const CATALOG: Record<string, Record<string, CatalogModel>> = {
  "anthropic": {
    "claude-sonnet-4-5": {"context":200000,"reasoning":true,"cost":{"input":3,"output":15,"cacheRead":0.3}},
    "claude-old": {"context":100000,"cost":{"input":8,"output":24}},
  },
  "openrouter": {
    "acme/model \\"quoted\\"": {"context":32000},
  },
};
`;

test("parseCatalog reads every provider and model of a generated catalog", () => {
  assert.deepEqual(parseCatalog(CATALOG_TEXT), {
    anthropic: {
      "claude-sonnet-4-5": {
        context: 200000,
        reasoning: true,
        cost: { input: 3, output: 15, cacheRead: 0.3 },
      },
      "claude-old": { context: 100000, cost: { input: 8, output: 24 } },
    },
    openrouter: { 'acme/model "quoted"': { context: 32000 } },
  });
});

test("parseCatalog reads the checked-in catalog", () => {
  const catalog = parseCatalog(
    readFileSync(
      new URL(
        "../../packages/llm-info/src/generated/catalog.ts",
        import.meta.url,
      ),
      "utf8",
    ),
  );
  const models = Object.values(catalog).flatMap((m) => Object.keys(m));
  // The sync refuses to write fewer than 500 models
  assert.ok(models.length >= 500, `${models.length} models`);
  assert.ok(catalog.anthropic);
});

test("a price, a limit and an effort change are listed with old and new values", () => {
  const before = parseCatalog(CATALOG_TEXT);
  const after = structuredClone(before);
  const sonnet = after.anthropic["claude-sonnet-4-5"];
  sonnet.cost.input = 4;
  delete sonnet.cost.cacheRead;
  sonnet.context = 1000000;
  sonnet.efforts = ["low", "high"];
  delete after.anthropic["claude-old"];
  after.anthropic["claude-new"] = { context: 300000 };

  assert.deepEqual(diffCatalogs(before, after), [
    {
      provider: "anthropic",
      added: ["claude-new"],
      removed: ["claude-old"],
      changed: [
        {
          id: "claude-sonnet-4-5",
          fields: [
            { path: "context", before: 200000, after: 1000000 },
            { path: "cost.cacheRead", before: 0.3, after: undefined },
            { path: "cost.input", before: 3, after: 4 },
            { path: "efforts", before: undefined, after: ["low", "high"] },
          ],
        },
      ],
    },
  ]);
  assert.deepEqual(formatDiff(diffCatalogs(before, after)), [
    "anthropic: 1 added, 1 removed, 1 changed",
    "  + claude-new",
    "  - claude-old",
    '  ~ claude-sonnet-4-5: context 200000 -> 1000000, cost.cacheRead 0.3 -> none, cost.input 3 -> 4, efforts none -> ["low","high"]',
  ]);
});

test("a new provider lists all its models as added", () => {
  const before = parseCatalog(CATALOG_TEXT);
  const after = { ...before, xai: { "grok-5": { context: 256000 } } };
  assert.deepEqual(formatDiff(diffCatalogs(before, after)), [
    "xai: 1 added, 0 removed, 0 changed",
    "  + grok-5",
  ]);
});

test("an unchanged catalog reports no change", () => {
  const catalog = parseCatalog(CATALOG_TEXT);
  assert.deepEqual(diffCatalogs(catalog, structuredClone(catalog)), []);
  assert.deepEqual(formatDiff([]), ["No model changed."]);
});
