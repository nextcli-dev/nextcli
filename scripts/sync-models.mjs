#!/usr/bin/env node
// Regenerates packages/llm-info/src/generated/catalog.ts from the models.dev
// catalog (https://models.dev/api.json): limits, reasoning efforts, image
// input, fast mode and prices, per provider. Only fields NextCLI reads are
// written; add one in the same change as the code that reads it.
//
//   npm run sync-models                 # download the catalog
//   npm run sync-models -- api.json     # use a saved copy
//
// The Sync models workflow (.github/workflows/sync-models.yml) runs it every
// Monday. When a model changed, the workflow updates the golden tests with
// vitest -u and opens a pull request that lists the models added and removed.
// MAINTAINING.md ("Model catalog") has the reviewer checklist. Run it by hand
// to pick up a change sooner, then review the same things. The snapshot is
// checked in, so nothing downloads it at runtime or in CI.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://models.dev/api.json";
const OUTPUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "packages",
  "llm-info",
  "src",
  "generated",
  "catalog.ts",
);

// models.dev provider ids kept in the snapshot. The NextCLI provider names
// that use them are in packages/llm-info/src/catalog.ts (CATALOG_PROVIDERS).
const PROVIDERS = [
  "amazon-bedrock",
  "anthropic",
  "azure",
  "cerebras",
  "cohere",
  "deepinfra",
  "deepseek",
  "fireworks-ai",
  "google",
  "google-vertex",
  "groq",
  "inception",
  "minimax",
  "mistral",
  "moonshotai",
  "nebius",
  "novita-ai",
  "nvidia",
  "openai",
  "openrouter",
  "ovhcloud",
  "sambanova",
  "scaleway",
  "togetherai",
  "xai",
  "zai",
];

async function loadCatalog(path) {
  if (path) {
    return JSON.parse(readFileSync(path, "utf8"));
  }
  const response = await fetch(SOURCE_URL, {
    headers: { "User-Agent": "nextcli-sync-models" },
  });
  if (!response.ok) {
    throw new Error(`${SOURCE_URL} returned ${response.status}`);
  }
  return response.json();
}

const isNumber = (value) => typeof value === "number" && Number.isFinite(value);

function trimCost(cost) {
  if (!cost || !isNumber(cost.input) || !isNumber(cost.output)) {
    return undefined;
  }
  const rates = { input: cost.input, output: cost.output };
  if (isNumber(cost.cache_read)) rates.cacheRead = cost.cache_read;
  if (isNumber(cost.cache_write)) rates.cacheWrite = cost.cache_write;
  return rates;
}

function trimModel(model) {
  const out = {};
  const limit = model.limit ?? {};
  // Some entries give 0 for an unknown limit
  if (isNumber(limit.context) && limit.context > 0) out.context = limit.context;
  if (isNumber(limit.input) && limit.input > 0) out.input = limit.input;
  if (model.reasoning) out.reasoning = true;
  for (const option of model.reasoning_options ?? []) {
    if (option.type === "effort" && Array.isArray(option.values)) {
      out.efforts = option.values;
    }
  }
  const inputs = model.modalities?.input ?? [];
  if (inputs.includes("image")) out.images = true;
  // Only a "no" is kept: most models take tools, and an absent flag must
  // not read as one
  if (model.tool_call === false) out.tools = false;
  // The request fields that turn fast mode on are the API rules' business
  // (modelControls.ts); the catalog says whether there is one, and its price
  const fast = model.experimental?.modes?.fast;
  if (fast?.provider) {
    const fastCost = trimCost(fast.cost);
    out.fast = fastCost ? { cost: fastCost } : {};
  }
  const cost = trimCost(model.cost);
  if (cost) {
    const tiers = (model.cost.tiers ?? [])
      .filter(
        (tier) => tier?.tier?.type === "context" && isNumber(tier.tier.size),
      )
      .map((tier) => ({ above: tier.tier.size, ...trimCost(tier) }))
      .filter((tier) => isNumber(tier.input));
    if (tiers.length > 0) cost.tiers = tiers;
    out.cost = cost;
  }
  if (model.status === "deprecated") out.deprecated = true;
  return out;
}

/** Chat models only: image, audio, video and embedding models are left out */
function isChatModel(model) {
  const outputs = model.modalities?.output ?? ["text"];
  return outputs.includes("text") && !/embed/i.test(model.id ?? "");
}

function render(catalog, syncedAt) {
  const lines = [
    "// Generated by scripts/sync-models.mjs (npm run sync-models). Do not edit",
    `// by hand. Source: ${SOURCE_URL}, read ${syncedAt}.`,
    'import type { CatalogModel } from "../catalogTypes.js";',
    "",
    `export const CATALOG_SYNCED_AT = "${syncedAt}";`,
    "",
    "export const CATALOG: Record<string, Record<string, CatalogModel>> = {",
  ];
  for (const provider of Object.keys(catalog).sort()) {
    lines.push(`  ${JSON.stringify(provider)}: {`);
    const models = catalog[provider];
    for (const id of Object.keys(models).sort()) {
      lines.push(`    ${JSON.stringify(id)}: ${JSON.stringify(models[id])},`);
    }
    lines.push("  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

/**
 * Model ids added and removed since the last snapshot, per provider. What
 * a sync changes in requests and prices shows in the golden tests
 * (catalogGolden.test.ts, calculateRequestCost.golden.vitest.ts).
 */
function summarize(previousText, catalog) {
  const previous = new Map();
  let provider;
  for (const line of previousText.split("\n")) {
    const providerMatch = line.match(/^ {2}"([^"]+)": \{$/);
    if (providerMatch) {
      provider = providerMatch[1];
      previous.set(provider, new Set());
      continue;
    }
    const modelMatch = line.match(/^ {4}"([^"]+)":/);
    if (modelMatch && provider) previous.get(provider).add(modelMatch[1]);
  }
  let changed = false;
  for (const [id, models] of Object.entries(catalog)) {
    const before = previous.get(id) ?? new Set();
    const now = new Set(Object.keys(models));
    const added = [...now].filter((m) => !before.has(m));
    const removed = [...before].filter((m) => !now.has(m));
    if (added.length || removed.length) {
      changed = true;
      console.log(`${id}: +${added.length} -${removed.length}`);
      for (const m of added) console.log(`  + ${m}`);
      for (const m of removed) console.log(`  - ${m}`);
    }
  }
  if (!changed) console.log("No models added or removed.");
}

const source = await loadCatalog(process.argv[2]);
const catalog = {};
for (const id of PROVIDERS) {
  const provider = source[id];
  if (!provider?.models) {
    throw new Error(`models.dev has no provider "${id}". Update PROVIDERS.`);
  }
  catalog[id] = {};
  for (const [modelId, model] of Object.entries(provider.models)) {
    if (isChatModel({ ...model, id: modelId })) {
      catalog[id][modelId] = trimModel(model);
    }
  }
}
const total = Object.values(catalog).reduce(
  (sum, models) => sum + Object.keys(models).length,
  0,
);
if (total < 500) {
  throw new Error(
    `Found only ${total} models. The catalog format may have changed.`,
  );
}

const syncedAt = new Date().toISOString().slice(0, 10);
if (existsSync(OUTPUT)) {
  summarize(readFileSync(OUTPUT, "utf8"), catalog);
}
const text = render(catalog, syncedAt);
writeFileSync(OUTPUT, text);
console.log(
  `Wrote ${total} models from ${PROVIDERS.length} providers (${Math.round(text.length / 1024)} KB) to ${OUTPUT}`,
);
