#!/usr/bin/env node
// Regenerates core/llm/utils/rates/openrouterRates.ts from the OpenRouter
// price table published at https://benchlm.ai/hosts/openrouter, which reads
// OpenRouter's public model catalog.
//
//   node scripts/update-openrouter-rates.mjs            # download the page
//   node scripts/update-openrouter-rates.mjs page.html  # use a saved copy
//
// Run it by hand when prices change, then format the output and review the
// diff:
//
//   npx prettier --write core/llm/utils/rates/openrouterRates.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://benchlm.ai/hosts/openrouter";
const OUTPUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "core",
  "llm",
  "utils",
  "rates",
  "openrouterRates.ts",
);

async function loadPage(path) {
  if (path) {
    return readFileSync(path, "utf8");
  }
  const response = await fetch(SOURCE_URL, {
    headers: { "User-Agent": "nextcli-rates-updater" },
  });
  if (!response.ok) {
    throw new Error(`${SOURCE_URL} returned ${response.status}`);
  }
  return response.text();
}

function readNumber(segment, key) {
  const match = segment.match(new RegExp(`"${key}":(-?[0-9.eE+-]+|null)`));
  if (!match || match[1] === "null") {
    return undefined;
  }
  const value = Number(match[1]);
  return Number.isFinite(value) ? value : undefined;
}

function parseRates(html) {
  const rates = new Map();
  const idPattern = /"hostModelId":"([^"]+)"/g;
  for (const match of html.matchAll(idPattern)) {
    const id = match[1];
    if (rates.has(id)) {
      continue;
    }
    // The fields of one row follow its id, before the next row starts.
    const segment = html
      .slice(match.index + match[0].length, match.index + 600)
      .split('"hostModelId"')[0];
    const input = readNumber(segment, "input");
    const output = readNumber(segment, "output");
    if (input === undefined || output === undefined) {
      continue;
    }
    const cachedInput = readNumber(segment, "cachedInput");
    rates.set(id, { input, output, cachedInput });
  }
  return rates;
}

function render(rates, retrievedAt) {
  const lines = [
    "// Generated by scripts/update-openrouter-rates.mjs. Do not edit by hand.",
    `// Source: ${SOURCE_URL} (OpenRouter's public model catalog).`,
    `// US dollars per million tokens, read ${retrievedAt}.`,
    'import type { HostRates } from "./hostRates";',
    "",
    `export const OPENROUTER_RATES_RETRIEVED_AT = "${retrievedAt}";`,
    "",
    "export const OPENROUTER_RATES: Record<string, HostRates> = {",
  ];
  for (const id of [...rates.keys()].sort()) {
    const { input, output, cachedInput } = rates.get(id);
    const cached =
      cachedInput === undefined ? "" : `, cachedInput: ${cachedInput}`;
    lines.push(
      `  ${JSON.stringify(id)}: { input: ${input}, output: ${output}${cached} },`,
    );
  }
  lines.push("};", "");
  return lines.join("\n");
}

const html = await loadPage(process.argv[2]);
const rates = parseRates(html);
if (rates.size < 100) {
  throw new Error(
    `Found only ${rates.size} models. The page layout may have changed.`,
  );
}
const retrievedAt =
  html.match(/"retrievedAt":"(\d{4}-\d{2}-\d{2})"/)?.[1] ??
  new Date().toISOString().slice(0, 10);
writeFileSync(OUTPUT, render(rates, retrievedAt));
console.log(`Wrote ${rates.size} models (read ${retrievedAt}) to ${OUTPUT}`);
